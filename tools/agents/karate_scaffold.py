# scenario and one guardrail (false-positive) scenario, anchored on the
# seeded MBR-00010..MBR-00012 / CLM-00050..CLM-00053 fixtures.

_RULE_TEMPLATES: dict[str, str] = {}


def _register_rule(code: str, body: str) -> None:
    _RULE_TEMPLATES[code] = body


