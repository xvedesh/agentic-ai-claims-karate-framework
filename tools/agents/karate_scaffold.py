"""Agent 3 - Karate Scaffold Generator.

Three sub-commands:

    scaffold from-openapi --spec docs/openapi/claims-api.yaml --tag claims
    scaffold from-rule    --rule FRAUD_DUPLICATE_CLAIM
    scaffold suggest

All output lands in ``generated/features/`` (gitignored). The SDET
reviews drafts and copies anything worth keeping into
``src/test/resources/features/`` by hand. The agent itself NEVER writes
into ``src/test/`` directly - this is enforced by the path constants in
``_common/paths.py``.

LLM enrichment is opt-in (``LLM_ENABLED=true``). The deterministic
fallback is template-based and produces feature files that compile and
run against the live server.
"""

