def _slug(rule: str) -> str:
    return rule.lower().replace("_", "-")


def from_rule(
    rule: Optional[str] = None,
    out: Optional[str] = None,
) -> int:
    if not rule:
        p.fail("--rule is required (e.g. FRAUD_DUPLICATE_CLAIM)")
        return 2
    code = rule.strip().upper()
    if code not in _RULE_TEMPLATES:
        p.fail(f"No template registered for rule {code}")
        p.warn("Templates are deliberately limited to the most-asked rules; "
               "the rest stay as `from-openapi` scaffolds. Edit "
               "tools/agents/karate_scaffold.py to add more.")
        return 3
    out_dir = paths.ensure_dir(Path(out) if out else paths.GENERATED_FEATURES) / "rules"
    out_dir.mkdir(parents=True, exist_ok=True)
    target = out_dir / f"{_slug(code)}.feature"
    body = _RULE_TEMPLATES[code]
    text = (
        f"{_HEADER.format(sub='from-rule')}"
        f"@generated @rules @{code.split('_', 1)[0].lower()}\n"
        f"Feature: {code} (generated draft)\n\n"
        f"  {body}"
    )
    target.write_text(text, encoding="utf-8")
    p.hr(f"Scaffold from rule: {code}")
    p.ok(f"Wrote {paths.safe_rel(target)}")
    p.warn("Review and copy by hand into src/test/resources/features/<category>/<rule>.feature.")
    return 0


