# from-openapi
# ---------------------------------------------------------------------------

@dataclass
class _OperationDraft:
    method: str
    path: str
    operation_id: str
    summary: str
    request_example: Any
    success_status: str
    error_statuses: list[str]
    requires_auth: bool


def _operations(spec: dict) -> list[_OperationDraft]:
    components = spec.get("components", {})
    out: list[_OperationDraft] = []
    for raw_path, ops in (spec.get("paths") or {}).items():
        if not isinstance(ops, dict):
            continue
        for method, op in ops.items():
            if method.lower() not in {"get", "post", "put", "patch", "delete"}:
                continue
            if not isinstance(op, dict):
                continue
            request_example = None
            req_body = op.get("requestBody")
            if isinstance(req_body, dict):
                schema = (
                    req_body.get("content", {})
                    .get("application/json", {})
                    .get("schema")
                )
                if schema:
                    request_example = _example_for(schema, components)
            responses = op.get("responses") or {}
            success = next(
                (code for code in responses if str(code).startswith("2")),
                "200",
            )
            errors = [c for c in responses if str(c).startswith(("4", "5"))]
            requires_auth = bool(op.get("security", [{"bearerAuth": []}])) and not (
                op.get("security") == []
            )
            op_id = op.get("operationId") or _safe_filename(f"{method}_{raw_path}")
            out.append(
                _OperationDraft(
                    method=method.upper(),
                    path=raw_path,
                    operation_id=op_id,
                    summary=op.get("summary", "").strip(),
                    request_example=request_example,
                    success_status=str(success),
                    error_statuses=[str(c) for c in errors],
                    requires_auth=requires_auth,
                )
            )
    return out


def _render_operation_feature(op: _OperationDraft, tag: str) -> str:
    body_block = ""
    if op.method in {"POST", "PUT", "PATCH"} and op.request_example is not None:
        pretty = json.dumps(op.request_example, indent=2, default=str)
        # Indent so the JSON aligns under `request`.
        pretty = "\n".join("      " + line for line in pretty.splitlines())
        body_block = f'    And request\n      """\n{pretty}\n      """\n'
    url_expr, path_params = _path_to_url_template(op.path)
    auth_block = (
        "    * call read('classpath:features/_common/reset.feature')\n"
        "    * configure headers = headers\n"
        if op.requires_auth
        else ""
    )
    # Placeholder defs for every path parameter so the draft compiles
    # before the SDET fills in real ids.
    param_defs = "".join(
        f"    * def {name} = 'TODO-{name.upper()}'\n" for name in path_params
    )

    method_call = op.method.lower()
    error_scenarios = ""
    if op.requires_auth and "401" in op.error_statuses:
        error_scenarios += (
            "\n  Scenario: 401 without bearer token\n"
            "    * configure headers = { Accept: 'application/json' }\n"
            + param_defs
            + f"    Given url baseUrl + {url_expr}\n"
            f"    When method {method_call}\n"
            "    Then status 401\n"
            "    And match response.error.code == 'UNAUTHORIZED'\n"
        )
    if "404" in op.error_statuses and path_params:
        # Substitute the first path parameter with a known-missing id.
        bad_url = url_expr.replace(path_params[0], f"'NOT-FOUND-{path_params[0].upper()}'", 1)
        error_scenarios += (
            "\n  Scenario: 404 for an unknown id\n"
            f"    Given url baseUrl + {bad_url}\n"
            f"    When method {method_call}\n"
            "    Then status 404\n"
            "    And match response.error.code == 'NOT_FOUND'\n"
        )

    return f"""{_HEADER.format(sub='from-openapi')}
@scaffold @{tag} @generated
Feature: {op.method} {op.path} - {op.summary or op.operation_id}

  Background:
{auth_block.rstrip() or '    # no auth required'}

  Scenario: positive ({op.success_status})
{param_defs}    Given url baseUrl + {url_expr}
{body_block}    When method {method_call}
    Then status {op.success_status}
{error_scenarios}"""


def from_openapi(
    spec: Optional[str] = None,
    tag: str = "claims",
    out: Optional[str] = None,
) -> int:
    spec_path = Path(spec) if spec else paths.OPENAPI_SPEC
    if not spec_path.is_file():
        p.fail(f"OpenAPI spec not found: {spec_path}")
        return 2
    out_dir = paths.ensure_dir(Path(out) if out else paths.GENERATED_FEATURES) / tag
    out_dir.mkdir(parents=True, exist_ok=True)

    p.hr(f"Scaffold from OpenAPI: {spec_path.name}  ->  {paths.safe_rel(out_dir)}/")
    spec_data = _load_openapi(spec_path)
    drafts = _operations(spec_data)
    if not drafts:
        p.warn("No operations found in spec.")
        return 1
    written = 0
    for op in drafts:
        feature = _render_operation_feature(op, tag=tag)
        # Operation ids from auto-generation already encode method + path
        # (e.g. "post_/api/claims"). Don't double-prefix when sanitising.
        base = op.operation_id
        if not base.lower().startswith(op.method.lower()):
            base = f"{op.method.lower()}_{base}"
        fname = _safe_filename(base) + ".feature"
        target = out_dir / fname
        target.write_text(feature, encoding="utf-8")
        written += 1
    p.ok(f"Generated {written} draft feature(s) under {paths.safe_rel(out_dir)}/")
    p.warn("Review carefully. The SDET copies into src/test/resources/features/ by hand.")
    return 0


