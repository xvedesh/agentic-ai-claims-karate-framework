_RULE_CODES = (
    "FRAUD_DUPLICATE_CLAIM",
    "FRAUD_PHANTOM_BILLING",
    "FRAUD_INVALID_PROVIDER",
    "ABUSE_UPCODING",
    "ABUSE_EXCESSIVE_FREQUENCY",
    "ABUSE_UNBUNDLING",
    "WASTE_DUPLICATE_SERVICE",
    "WASTE_MEDICALLY_UNLIKELY_UNITS",
    "WASTE_UNNECESSARY_PATTERN",
)


def _scan_features_for_codes() -> dict[str, list[str]]:
    """Return rule -> [feature paths that mention it]."""
    coverage: dict[str, list[str]] = {c: [] for c in _RULE_CODES}
    if not paths.KARATE_FEATURES.exists():
        return coverage
    for feature in paths.KARATE_FEATURES.rglob("*.feature"):
        text = feature.read_text(encoding="utf-8", errors="replace")
        rel = feature.relative_to(paths.ROOT).as_posix()
        for code in _RULE_CODES:
            if code in text:
                coverage[code].append(rel)
    return coverage


def suggest() -> int:
    coverage = _scan_features_for_codes()
    paths.ensure_dir(paths.REPORTS_DIR)
    target = paths.REPORTS_DIR / "test-generation-plan.md"
    lines = ["# Test Generation Plan", ""]
    lines.append("Coverage matrix between the 9 catalogued rule codes and the\n"
                 "Karate features under `src/test/resources/features/`:\n")
    lines.append("| Rule code | Coverage | Mentioned in |")
    lines.append("|---|---|---|")
    uncovered: list[str] = []
    for code, hits in coverage.items():
        if hits:
            lines.append(f"| `{code}` | OK | {', '.join(f'`{h}`' for h in hits)} |")
        else:
            uncovered.append(code)
            lines.append(f"| `{code}` | **MISSING** | _(no scenario references this code)_ |")
    if uncovered:
        lines.append("")
        lines.append("## Suggested next actions")
        lines.append("")
        for code in uncovered:
            lines.append(f"- Run `python -m tools.cli scaffold from-rule --rule {code}` to draft a starting feature.")
    else:
        lines.append("")
        lines.append("All 9 rule codes appear in at least one Karate feature.")
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    p.hr("Coverage suggestion")
    p.ok(f"Wrote {paths.safe_rel(target)}")
    if uncovered:
        p.warn(f"Missing rule coverage: {', '.join(uncovered)}")
    else:
        p.ok("All 9 rule codes covered.")
    return 0
