_HEADER = """\
# Generated by `python -m tools.cli scaffold {sub}`.
# DO NOT promote this file directly to src/test/resources/features/.
# Review it, edit assertions to match real behaviour, then copy by hand.
"""


def _load_openapi(spec_path: Path) -> dict:
    return yaml.safe_load(spec_path.read_text(encoding="utf-8"))


def _example_for(schema: dict, components: dict, depth: int = 0) -> Any:
    """Best-effort example value for a JSON-Schema-ish node."""
    if depth > 6:
        return None
    if "$ref" in schema:
        ref = schema["$ref"].split("/")[-1]
        target = components.get("schemas", {}).get(ref)
        if not target:
            return None
        return _example_for(target, components, depth + 1)
    if "example" in schema:
        return schema["example"]
    t = schema.get("type")
    if t == "object" or "properties" in schema:
        out: dict[str, Any] = {}
        props = schema.get("properties", {})
        required = set(schema.get("required", []))
        for name, sub in props.items():
            if required and name not in required:
                continue
            out[name] = _example_for(sub, components, depth + 1)
        return out
    if t == "array":
        return [_example_for(schema.get("items", {}), components, depth + 1)]
    if t == "integer":
        return schema.get("minimum", 1)
    if t == "number":
        return schema.get("minimum", 0)
    if t == "boolean":
        return True
    if t == "string":
        if schema.get("enum"):
            return schema["enum"][0]
        if schema.get("format") == "date":
            return "2026-04-10"
        if schema.get("format") == "date-time":
            return "2026-04-10T00:00:00.000Z"
        return "synthetic"
    return None


def _safe_filename(s: str) -> str:
    s = re.sub(r"[^A-Za-z0-9_\-]+", "_", s.strip("/"))
    return re.sub(r"_+", "_", s).strip("_") or "scaffold"


def _path_to_url_template(path: str) -> tuple[str, list[str]]:
    """Convert /api/claims/{id}/submit into ('/api/claims/' + id + '/submit', ['id']).

    Returns the Karate-DSL URL expression and the ordered list of path
    parameter names so the renderer can emit ``* def id = 'TODO'`` lines.
    """
    parts = re.split(r"(\{[^}]+\})", path)
    chunks: list[str] = []
    params: list[str] = []
    for part in parts:
        if not part:
            continue
        if part.startswith("{") and part.endswith("}"):
            name = part[1:-1]
            chunks.append(name)
            params.append(name)
        else:
            chunks.append(repr(part))
    return " + ".join(chunks), params


